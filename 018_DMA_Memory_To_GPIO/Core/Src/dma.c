/**
 * @brief  DMA 传输完成回调函数
 * @note   每次传输完成后切换源数据，并重新启动 DMA，实现 GPIO 电平交替输出
 * @param  _hdma 触发本次回调的 DMA 句柄
 * @retval None
 */
void my_dma_full_transfer_complete(DMA_HandleTypeDef *_hdma)
{
    static uint8_t counter = 0;
    counter++;
    HAL_DMA_Start_IT(&hdma_memtomem_dma2_stream0,
                   (uint32_t)&src_data[counter%2],
                   (uint32_t)&GPIOA->ODR,
                   1);
}
